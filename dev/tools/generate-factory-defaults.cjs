const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..', '..', 'app');
const sources = Object.fromEntries(['circle', 'square', 'linear'].map(layout => {
    const file = path.join(root, '..', 'dev', 'fixtures', 'factory-defaults', layout + '.json');
    const bytes = fs.readFileSync(file);
    const preset = JSON.parse(bytes.toString('utf8').replace(/^\uFEFF/, ''));
    if (preset.format !== 'audio-visualizer-preset' || preset.version !== 1 || preset.standalone.visualizer.layout !== layout) throw new Error('Invalid factory source: ' + layout);
    return [layout, { sha256: crypto.createHash('sha256').update(bytes).digest('hex'), preset }];
}));
const output = '// Generated by scripts/generate-factory-defaults.cjs. Source snapshots are immutable.\n'
    + '(function () {\n    function freeze(value) {\n        if (value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); }\n        return value;\n    }\n'
    + '    window.VisualizerFactorySources = freeze(' + JSON.stringify(sources, null, 4) + ');\n}());\n';
const target = path.join(root, 'factory-defaults-data.js');
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Factory data is stale');
    console.log('Factory source snapshots verified: Circle / Square / Linear');
} else fs.writeFileSync(target, output);
